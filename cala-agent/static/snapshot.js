const contextTypes = new Set([
  "OPERATES_IN_INDUSTRY", "HAS_HEADQUARTERS_IN", "IS_REGISTERED_IN"
]);

export function indexSnapshot(report) {
  const { attendees, edges, max_hops: maxHops } = report.network;
  if (!Array.isArray(attendees) || !Array.isArray(edges) ||
      !Number.isInteger(maxHops) || maxHops < 1 || !report.coverage) {
    throw new Error("Expected a report generated by scan_export.py.");
  }
  const entities = new Map(attendees.map(entity => [entity.id, entity]));
  const adjacency = new Map();
  const byId = new Map();
  for (const edge of edges) {
    byId.set(edge.pointer, edge);
    for (const endpoint of [edge.source, edge.target]) {
      entities.set(endpoint.id, endpoint);
      if (!adjacency.has(endpoint.id)) adjacency.set(endpoint.id, []);
      adjacency.get(endpoint.id).push(edge);
    }
  }
  return { attendees, entities, adjacency, byId, maxHops };
}

export function findRoutes(index, start, includeContext) {
  const parents = new Map([[start, null]]);
  const queue = [{ id: start, depth: 0 }];
  for (let cursor = 0; cursor < queue.length; cursor++) {
    const { id, depth } = queue[cursor];
    if (depth >= index.maxHops) continue;
    for (const edge of index.adjacency.get(id) || []) {
      if (!includeContext && contextTypes.has(edge.type)) continue;
      const next = edge.source.id === id ? edge.target.id : edge.source.id;
      if (parents.has(next)) continue;
      parents.set(next, { id, edge });
      queue.push({ id: next, depth: depth + 1 });
    }
  }
  const routes = new Map();
  for (const attendee of index.attendees) {
    if (attendee.id === start || !parents.has(attendee.id)) continue;
    const path = [];
    for (let id = attendee.id; id !== start; ) {
      const step = parents.get(id);
      path.push(step.edge);
      id = step.id;
    }
    routes.set(attendee.id, path.reverse());
  }
  return routes;
}

export function bindSnapshot(network, nodes, edges) {
  const element = id => document.getElementById(`snapshot-${id}`);
  const focus = element("focus");
  const target = element("target");
  const context = element("context");
  const evidence = element("evidence");
  let index;
  let routes;
  let loadVersion = 0;

  function draw() {
    const path = routes.get(target.value);
    const visible = path || (index.adjacency.get(focus.value) || [])
      .filter(edge => context.checked || !contextTypes.has(edge.type));
    const pathIds = new Set(visible.flatMap(edge => [edge.source.id, edge.target.id]));
    pathIds.add(focus.value);
    edges.clear();
    nodes.clear();
    nodes.add([...pathIds].map(id => {
      const entity = index.entities.get(id);
      const isPerson = entity.entity_type === "Person";
      return {
        id,
        label: entity.name || id,
        color: id === focus.value ? "#ffc234" : isPerson ? "#dff2ff" : "#fcf8f0",
        font: { color: "#2e2723" }
      };
    }));
    // Keep parallel relationship records visible for the node pair on each step.
    const shown = new Map();
    for (const edge of visible) {
      for (const parallel of index.adjacency.get(edge.source.id)) {
        if (!context.checked && contextTypes.has(parallel.type)) continue;
        const samePair = parallel.source.id === edge.source.id && parallel.target.id === edge.target.id;
        const reversePair = parallel.source.id === edge.target.id && parallel.target.id === edge.source.id;
        if (!samePair && !reversePair) continue;
        shown.set(parallel.pointer, {
          id: parallel.pointer, from: parallel.source.id, to: parallel.target.id,
          arrows: "to", label: parallel.type.replaceAll("_", " ")
        });
      }
    }
    edges.add([...shown.values()]);
    network.fit();
    element("path").textContent = path
      ? `${path.length} hops to ${index.entities.get(target.value).name || target.value}.`
      : routes.size
        ? "Showing neighboring entities. Choose a Slush attendee to draw a path."
        : "No route to another Slush attendee found with these settings. Showing available neighbors.";
    evidence.textContent = "Select an edge to inspect its evidence.";
  }

  function selectFocus() {
    routes = findRoutes(index, focus.value, context.checked);
    const previous = target.value;
    target.replaceChildren(new Option("Show neighbors", ""));
    for (const [id, path] of [...routes].sort(([a, x], [b, y]) =>
      x.length - y.length || (index.entities.get(a).name || a).localeCompare(index.entities.get(b).name || b))) {
      target.add(new Option(`${index.entities.get(id).name || id} (${path.length} hops)`, id));
    }
    target.value = routes.has(previous) ? previous : "";
    draw();
  }

  function load(report) {
    const next = indexSnapshot(report);
    const rows = [...next.entities.values()].sort((a, b) =>
      (a.name || a.id).localeCompare(b.name || b.id));
    if (!rows.length) throw new Error("The report has no entities to display.");
    index = next;
    focus.replaceChildren(...rows.map(entity =>
      new Option(`${entity.name || entity.id} · ${entity.entity_type || "Entity"}`, entity.id)));
    focus.value = rows.find(entity => entity.name === "Bliq" && index.adjacency.has(entity.id))?.id
      || rows.find(entity => index.adjacency.has(entity.id))?.id || rows[0].id;
    const coverage = report.coverage;
    element("coverage").textContent =
      `${coverage.complete ? "Complete export" : "Partial export"} · ` +
      `${coverage.company_attendees_with_retrieved_records} of ${coverage.listed_company_attendees} ` +
      `attendee company records retrieved · Up to ${index.maxHops} hops.`;
    selectFocus();
    element("controls").hidden = false;
    element("status").textContent = `Showing ${report.event?.name || "Slush"} export data.`;
    document.getElementById("connections-panel").hidden = true;
    document.querySelector(".graph-glass-note").hidden = true;
  }

  element("file").addEventListener("change", async event => {
    const file = event.target.files[0];
    if (!file) return;
    const version = ++loadVersion;
    try {
      const report = JSON.parse(await file.text());
      if (version === loadVersion) load(report);
    } catch {
      if (version === loadVersion) element("status").textContent =
        "Could not open this file. Choose the JSON report generated by scan_export.py.";
    }
  });
  focus.addEventListener("change", selectFocus);
  context.addEventListener("change", selectFocus);
  target.addEventListener("change", draw);
  network.on("click", ({ edges: selected, nodes: clicked }) => {
    if (!index || clicked.length) return;
    const edge = index.byId.get(selected[0]);
    if (!edge) return;
    const heading = document.createElement("strong");
    heading.textContent =
      `${edge.source.name || edge.source.id} → ${edge.type} → ${edge.target.name || edge.target.id}`;
    const details = document.createElement("p");
    const properties = (edge.properties || []).flatMap(row =>
      Object.entries(row).filter(([key]) => key !== "id")
        .map(([key, value]) => `${key.replaceAll("_", " ")}: ${typeof value === "string" ? value : JSON.stringify(value)}`));
    details.textContent = [...new Set(properties)].join(" · ");
    const pointer = document.createElement("p");
    pointer.textContent = `Export reference ${edge.pointer}`;
    const sources = document.createElement("ul");
    for (const source of edge.sources) {
      const item = document.createElement("li");
      item.textContent = [source.name, source.date].filter(Boolean).join(" · ");
      if (/^https?:\/\//i.test(source.document || "")) {
        const link = document.createElement("a");
        link.href = source.document;
        link.target = "_blank";
        link.rel = "noopener noreferrer";
        link.textContent = "Open source";
        item.append(" ", link);
      }
      sources.append(item);
    }
    if (!edge.sources.length) {
      const item = document.createElement("li");
      item.textContent = "Cala supplied no source for this edge.";
      sources.append(item);
    }
    evidence.replaceChildren(heading, details, pointer, sources);
  });
  network.on("doubleClick", ({ nodes: clicked }) => {
    if (!index || !clicked.length) return;
    focus.value = clicked[0];
    selectFocus();
  });

  fetch("/slush/snapshot").then(response => {
    if (response.status === 404) return null;
    if (!response.ok) throw new Error("Snapshot unavailable");
    return response.json();
  })
    .then(report => { if (report && loadVersion === 0) load(report); })
    .catch(() => {
      if (loadVersion === 0) element("status").textContent =
        "Could not load the configured report. You can open a scanner report here.";
    });
}
